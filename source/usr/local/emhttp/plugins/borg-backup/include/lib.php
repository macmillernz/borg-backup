/** Create a directory (recursively) if needed and return it. */
function bb_dir(string $d): string {
  if (!is_dir($d)) @mkdir($d, 0700, true);
  return $d;
}

/** Load a JSON document from the config dir, or $default if missing/corrupt. */
function bb_load(string $name, $default = []) {
  $f = BB_CFG . "/$name.json";
  if (!is_file($f)) return $default;
  $d = json_decode((string)@file_get_contents($f), true);
  return is_array($d) ? $d : $default;
}

/** Atomically write a JSON document to the config dir. */
function bb_save(string $name, $data): void {
  bb_dir(BB_CFG);
  $f = BB_CFG . "/$name.json";
  $tmp = "$f.tmp" . getmypid();
  file_put_contents($tmp, json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
  rename($tmp, $f);
}

/**
 * Read-modify-write a JSON document under an exclusive lock so the web UI
 * and running jobs never overwrite each other's changes.
 * @param callable $fn receives the current data, returns the new data
 */
function bb_update(string $name, callable $fn, $default = []) {
  bb_dir(BB_RUN);
  $lock = fopen(BB_RUN . "/$name.lock", 'c');
  flock($lock, LOCK_EX);
  try {
    $data = $fn(bb_load($name, $default));
    bb_save($name, $data);
    return $data;
  } finally {
    flock($lock, LOCK_UN);
    fclose($lock);
  }
}

/** Generate a short random id. */
function bb_id(): string {
  return bin2hex(random_bytes(5));
}

/** True for ids generated by bb_id() (and similar safe tokens). */
function bb_valid_id($id): bool {
  return is_string($id) && preg_match('/^[a-z0-9]{4,32}$/', $id) === 1;
}

/** Turn a free-text name into a safe archive prefix. */
function bb_slug(string $s): string {
  $s = strtolower(preg_replace('/[^A-Za-z0-9]+/', '-', $s));
  return trim($s, '-') ?: 'backup';
}

