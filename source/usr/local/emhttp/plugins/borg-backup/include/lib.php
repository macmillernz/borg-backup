/** Convert a schedule object to a cron expression (null = manual only). */
function bb_schedule_cron(?array $s): ?string {
  $s = $s ?: ['preset' => 'manual'];
  [$h, $m] = array_map('intval', explode(':', ($s['time'] ?? '02:00') . ':0'));
  $h = max(0, min(23, $h)); $m = max(0, min(59, $m));
  switch ($s['preset'] ?? 'manual') {
    case 'hourly':  return sprintf('%d * * * *', max(0, min(59, (int)($s['minute'] ?? 0))));
    case 'daily':   return "$m $h * * *";
    case 'weekly':  return "$m $h * * " . max(0, min(6, (int)($s['dow'] ?? 0)));
    case 'monthly': return "$m $h " . max(1, min(28, (int)($s['dom'] ?? 1))) . ' * *';
    case 'custom':  return bb_cron_valid($s['cron'] ?? '') ? trim(preg_replace('/\s+/', ' ', $s['cron'])) : null;
  }
  return null;
}

/** Only allow plain 5-field cron expressions (prevents crontab injection). */
function bb_cron_valid(string $c): bool {
  $f = preg_split('/\s+/', trim($c));
  if (count($f) !== 5) return false;
  foreach ($f as $x) if (!preg_match('#^[0-9*,/-]+$#', $x)) return false;
  return true;
}

/** Human readable schedule. */
function bb_schedule_text(?array $s): string {
  $s = $s ?: ['preset' => 'manual'];
  $days = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  switch ($s['preset'] ?? 'manual') {
    case 'hourly':  return sprintf('Hourly at :%02d', (int)($s['minute'] ?? 0));
    case 'daily':   return 'Daily at ' . ($s['time'] ?? '02:00');
    case 'weekly':  return 'Every ' . $days[(int)($s['dow'] ?? 0) % 7] . ' at ' . ($s['time'] ?? '02:00');
    case 'monthly': return 'Monthly on day ' . (int)($s['dom'] ?? 1) . ' at ' . ($s['time'] ?? '02:00');
    case 'custom':  return 'Cron: ' . ($s['cron'] ?? '');
  }
  return 'Manual';
}

/** Does a cron field match a value? */
function bb_cron_match(string $field, int $v, int $min, int $max): bool {
  foreach (explode(',', $field) as $part) {
    $step = 1; $hasStep = false;
    if (strpos($part, '/') !== false) { [$part, $step] = explode('/', $part); $step = max(1, (int)$step); $hasStep = true; }
    if ($part === '*') { $lo = $min; $hi = $max; }
    elseif (strpos($part, '-') !== false) { [$lo, $hi] = array_map('intval', explode('-', $part)); }
    else { $lo = (int)$part; $hi = $hasStep ? $max : $lo; }
    if ($v >= $lo && $v <= $hi && (($v - $lo) % $step) === 0) return true;
  }
  return false;
}

/** Next run time (unix ts) of a cron expression after $from, within ~1 year. */
function bb_cron_next(?string $expr, ?int $from = null): ?int {
  if (!$expr || !bb_cron_valid($expr)) return null;
  [$mi, $ho, $dom, $mon, $dow] = preg_split('/\s+/', trim($expr));
  $t = ($from ?? time()) + 60;
  $t -= $t % 60;
  $day = strtotime(date('Y-m-d 00:00:00', $t));
  for ($d = 0; $d < 400; $d++, $day = strtotime('+1 day', $day)) {
    $mOk = bb_cron_match($mon, (int)date('n', $day), 1, 12);
    if (!$mOk) continue;
    $domOk = bb_cron_match($dom, (int)date('j', $day), 1, 31);
    $w = (int)date('w', $day);
    $dowOk = bb_cron_match($dow, $w, 0, 7) || ($w === 0 && bb_cron_match($dow, 7, 0, 7));
    $ok = ($dom !== '*' && $dow !== '*') ? ($domOk || $dowOk) : ($domOk && $dowOk);
    if (!$ok) continue;
    for ($h = 0; $h < 24; $h++) {
      if (!bb_cron_match($ho, $h, 0, 23)) continue;
      for ($m = 0; $m < 60; $m++) {
        if (!bb_cron_match($mi, $m, 0, 59)) continue;
        $ts = mktime($h, $m, 0, (int)date('n', $day), (int)date('j', $day), (int)date('Y', $day));
        if ($ts >= $t) return $ts;
      }
    }
  }
  return null;
}

/** Regenerate the plugin cron file from enabled jobs and tests, then reload cron. */
function bb_write_cron(): void {
  $php = is_executable('/usr/bin/php') ? '/usr/bin/php' : 'php';
  $runner = BB_EMHTTP . '/include/runner.php';
  $lines = ["# Generated by the borg-backup plugin - do not edit"];
  foreach (bb_load('jobs') as $j) {
    $c = bb_schedule_cron($j['schedule'] ?? null);
    if ($c && !empty($j['enabled'])) $lines[] = "$c $php $runner job {$j['id']} >/dev/null 2>&1";
  }
  foreach (bb_load('tests') as $t) {
    $c = bb_schedule_cron($t['schedule'] ?? null);
    if ($c && !empty($t['enabled'])) $lines[] = "$c $php $runner test {$t['id']} >/dev/null 2>&1";
  }
  bb_dir(BB_CFG);
  file_put_contents(BB_CFG . '/borg-backup.cron', implode("\n", $lines) . "\n");
  if (is_executable('/usr/local/sbin/update_cron')) exec('/usr/local/sbin/update_cron >/dev/null 2>&1');
}

