/**
 * Run a command without a shell.
 *
 * @param array         $cmd     argv
 * @param array         $env     extra environment (merged over a sane base)
 * @param array         $opt     cwd, timeout (s), on_line(callable $line, $stream),
 *                               on_start(callable $pid), stdout_file (path), input (string)
 * @param string|null   $out     captured stdout (unless stdout_file is used)
 * @param string|null   $err     captured stderr
 * @return int exit code (124 on timeout, 127 if it could not start)
 */
function bb_exec(array $cmd, array $env = [], array $opt = [], &$out = null, &$err = null): int {
  $out = ''; $err = '';
  $base = ['PATH' => BB_PATH, 'HOME' => '/root', 'LANG' => 'C', 'PYTHONUTF8' => '1']; // Unraid has no C.UTF-8 locale; borg (Python) still uses UTF-8 via PYTHONUTF8
  $spec = [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']];
  if (!empty($opt['stdout_file'])) $spec[1] = ['file', $opt['stdout_file'], 'w'];
  $p = @proc_open($cmd, $spec, $pipes, $opt['cwd'] ?? null, array_merge($base, $env));
  if (!is_resource($p)) { $err = 'Could not start ' . $cmd[0]; return 127; }
  if (!empty($opt['on_start'])) $opt['on_start'](proc_get_status($p)['pid']);
  if (isset($opt['input'])) fwrite($pipes[0], $opt['input']);
  fclose($pipes[0]);
  $streams = [];
  if (isset($pipes[1])) $streams[1] = $pipes[1];
  $streams[2] = $pipes[2];
  foreach ($streams as $s) stream_set_blocking($s, false);
  $buf = [1 => '', 2 => ''];
  $deadline = !empty($opt['timeout']) ? microtime(true) + $opt['timeout'] : null;
  $timedOut = false;
  while ($streams) {
    $r = array_values($streams); $w = $x = null;
    if (@stream_select($r, $w, $x, 1) === false) break;
    foreach ($r as $s) {
      $k = array_search($s, $streams, true);
      $chunk = fread($s, 65536);
      if ($chunk === '' || $chunk === false) {
        if (feof($s)) { fclose($s); unset($streams[$k]); }
        continue;
      }
      if ($k === 1) $out .= $chunk; else $err .= $chunk;
      if (!empty($opt['on_line'])) {
        $buf[$k] .= $chunk;
        while (($pos = strpos($buf[$k], "\n")) !== false) {
          $opt['on_line'](rtrim(substr($buf[$k], 0, $pos), "\r"), $k);
          $buf[$k] = substr($buf[$k], $pos + 1);
        }
      }
    }
    if ($deadline && microtime(true) > $deadline) {
      proc_terminate($p, 15); $timedOut = true; break;
    }
  }
  if (!empty($opt['on_line'])) foreach ($buf as $k => $b) if ($b !== '') $opt['on_line']($b, $k);
  foreach ($streams as $s) fclose($s);
  // proc_close's return value is unreliable once proc_get_status saw the exit, so poll.
  $code = -1;
  for ($i = 0; $i < 600; $i++) {
    $st = proc_get_status($p);
    if (!$st['running']) { $code = $st['exitcode']; break; }
    usleep(100000);
  }
  $rc = proc_close($p);
  if ($code === -1) $code = $rc;
  return $timedOut ? 124 : $code;
}

