/** Run the docker CLI; returns [rc, stdout, stderr]. */
function bb_docker(array $args, int $timeout = 60): array {
  $rc = bb_exec(array_merge(['docker'], $args), [], ['timeout' => $timeout], $out, $err);
  return [$rc, $out, $err];
}

/** All containers: [{name, image, state, project}] */
function bb_containers(): array {
  [$rc, $out] = bb_docker(['ps', '-a', '--format', '{{json .}}']);
  if ($rc !== 0) return [];
  $list = [];
  foreach (explode("\n", trim($out)) as $line) {
    $c = json_decode($line, true);
    if (!$c) continue;
    $project = null;
    if (preg_match('/(?:^|,)com\.docker\.compose\.project=([^,]+)/', $c['Labels'] ?? '', $m)) $project = $m[1];
    $list[] = ['name' => $c['Names'], 'image' => $c['Image'], 'state' => $c['State'], 'status' => $c['Status'], 'project' => $project];
  }
  usort($list, fn($a, $b) => strcasecmp($a['name'], $b['name']));
  return $list;
}

/** Paths that should never be offered as backup sources by default. */
function bb_default_include(string $path, string $type): bool {
  foreach (['/var/run/docker.sock', '/dev', '/proc', '/sys', '/etc/localtime', '/tmp', '/run', '/var/run', '/etc/timezone'] as $x) {
    if ($path === $x || strpos($path, "$x/") === 0) return false;
  }
  if ($type === 'volume') return true;
  return preg_match('#/appdata(/|$)#i', $path) === 1;
}

/** Normalise a mount entry for the UI. */
function bb_mount(string $source, string $target, string $type, bool $ro, string $origin): array {
  return ['path' => $source, 'target' => $target, 'type' => $type, 'ro' => $ro,
          'origin' => $origin, 'exists' => file_exists($source), 'include' => bb_default_include($source, $type)];
}

/** Mounts of one or more containers via `docker inspect`. */
function bb_container_mounts(array $names): array {
  if (!$names) return [];
  [$rc, $out] = bb_docker(array_merge(['inspect'], $names));
  $mounts = [];
  foreach ((json_decode($out, true) ?: []) as $c) {
    $cname = ltrim($c['Name'] ?? '', '/');
    foreach ($c['Mounts'] ?? [] as $m) {
      if (empty($m['Source'])) continue;
      $mounts[$m['Source']] = bb_mount($m['Source'], $m['Destination'] ?? '', $m['Type'] ?? 'bind', empty($m['RW']), $cname);
    }
  }
  return array_values($mounts);
}

/** Lowercase/sanitise like compose does for project names. */
function bb_compose_project_name(string $s): string {
  return preg_replace('/[^a-z0-9_-]/', '', strtolower($s));
}

/** First compose file found in a directory. */
function bb_find_compose_file(string $dir): ?string {
  foreach (['docker-compose.yml', 'docker-compose.yaml', 'compose.yaml', 'compose.yml'] as $f) {
    if (is_file("$dir/$f")) return "$dir/$f";
  }
  return null;
}

/**
 * Discover compose stacks from the Compose Manager plugin and from running
 * containers' compose labels.
 * @return array name => [name, project, files[], env_file, dir, source, containers[]]
 */
function bb_compose_stacks(): array {
  $stacks = [];
  // 1. Compose Manager plugin projects
  foreach (glob(BB_COMPOSE_MANAGER . '/*', GLOB_ONLYDIR) ?: [] as $pdir) {
    $folder = basename($pdir);
    $dir = $pdir;
    if (is_file("$pdir/indirect")) $dir = rtrim(trim(file_get_contents("$pdir/indirect")), '/');
    $file = bb_find_compose_file($dir);
    if (!$file) continue;
    $files = [$file];
    if (is_file("$pdir/docker-compose.override.yml")) $files[] = "$pdir/docker-compose.override.yml";
    $env = is_file("$pdir/envpath") ? trim(file_get_contents("$pdir/envpath")) : "$dir/.env";
    $display = is_file("$pdir/name") ? trim(file_get_contents("$pdir/name")) : $folder;
    $project = bb_compose_project_name($folder);
    $stacks[$project] = ['name' => $display, 'project' => $project, 'files' => $files,
      'env_file' => is_file($env) ? $env : null, 'dir' => $dir, 'source' => 'Compose Manager', 'containers' => []];
  }
  // 2. Anything the docker daemon knows via compose labels (Dockge, CLI, etc.)
  [$rc, $out] = bb_docker(['ps', '-a', '--format', '{{.Names}}|{{.Label "com.docker.compose.project"}}|{{.Label "com.docker.compose.project.config_files"}}|{{.Label "com.docker.compose.project.working_dir"}}|{{.State}}']);
  foreach (explode("\n", trim($rc === 0 ? $out : '')) as $line) {
    $p = explode('|', $line);
    if (count($p) < 5 || $p[1] === '') continue;
    [$cname, $project, $cfg, $wd, $state] = $p;
    if (!isset($stacks[$project])) {
      $files = array_values(array_filter(explode(',', $cfg), 'is_file'));
      $env = $wd && is_file("$wd/.env") ? "$wd/.env" : null;
      $stacks[$project] = ['name' => $project, 'project' => $project, 'files' => $files,
        'env_file' => $env, 'dir' => $wd, 'source' => 'Docker labels', 'containers' => []];
    }
    $stacks[$project]['containers'][] = ['name' => $cname, 'state' => $state];
  }
  ksort($stacks);
  return $stacks;
}

/**
 * Resolve the host paths a compose stack mounts. Uses `docker compose config`
 * so variables from .env / env files are interpolated; falls back to inspecting
 * the stack's containers when the compose CLI is not usable.
 */
function bb_compose_mounts(array $stack): array {
  $mounts = [];
  $error = null;
  if ($stack['files']) {
    $args = ['compose'];
    foreach ($stack['files'] as $f) array_push($args, '-f', $f);
    if (!empty($stack['env_file'])) array_push($args, '--env-file', $stack['env_file']);
    if (!empty($stack['dir']) && is_dir($stack['dir'])) array_push($args, '--project-directory', $stack['dir']);
    array_push($args, '-p', $stack['project'], 'config', '--format', 'json');
    [$rc, $out, $err] = bb_docker($args);
    $cfg = $rc === 0 ? json_decode($out, true) : null;
    if ($cfg) {
      foreach ($cfg['services'] ?? [] as $svc => $def) {
        foreach ($def['volumes'] ?? [] as $v) {
          $type = $v['type'] ?? 'bind';
          $src = $v['source'] ?? '';
          if ($type === 'volume' && $src !== '') {
            $vname = $cfg['volumes'][$src]['name'] ?? ($stack['project'] . '_' . $src);
            [$vrc, $vout] = bb_docker(['volume', 'inspect', '--format', '{{.Mountpoint}}', $vname]);
            $src = $vrc === 0 ? trim($vout) : "/var/lib/docker/volumes/$vname/_data";
          }
          if ($src === '' || $type === 'tmpfs') continue;
          $mounts[$src] = bb_mount($src, $v['target'] ?? '', $type, !empty($v['read_only']), $svc);
        }
      }
      return ['mounts' => array_values($mounts), 'error' => null, 'method' => 'docker compose config'];
    }
    $error = trim($err) ?: 'docker compose config failed';
  }
  $names = array_column($stack['containers'] ?: bb_project_containers($stack['project']), 'name');
  return ['mounts' => bb_container_mounts($names), 'error' => $error, 'method' => 'docker inspect'];
}

/** Containers belonging to a compose project: [{name, state}] */
function bb_project_containers(string $project): array {
  [$rc, $out] = bb_docker(['ps', '-a', '--filter', "label=com.docker.compose.project=$project", '--format', '{{.Names}}|{{.State}}']);
  $list = [];
  foreach (explode("\n", trim($rc === 0 ? $out : '')) as $l) {
    if ($l === '') continue;
    [$n, $s] = explode('|', $l) + [1 => ''];
    $list[] = ['name' => $n, 'state' => $s];
  }
  return $list;
}

/**
 * Order containers so compose dependencies start first (uses the
 * com.docker.compose.depends_on / .service labels when present).
 */
function bb_start_order(array $names): array {
  if (count($names) < 2) return $names;
  [$rc, $out] = bb_docker(array_merge(['inspect', '--format',
    '{{.Name}}|{{index .Config.Labels "com.docker.compose.service"}}|{{index .Config.Labels "com.docker.compose.depends_on"}}'], $names));
  if ($rc !== 0) return $names;
  $svc = []; $deps = [];
  foreach (explode("\n", trim($out)) as $l) {
    [$n, $s, $d] = explode('|', $l) + [1 => '', 2 => ''];
    $n = ltrim($n, '/');
    if ($s !== '') $svc[$s] = $n;
    $deps[$n] = array_filter(array_map(fn($x) => explode(':', $x)[0], explode(',', $d)));
  }
  $ordered = []; $seen = [];
  $visit = function ($n, $depth = 0) use (&$visit, &$ordered, &$seen, $deps, $svc) {
    if (isset($seen[$n]) || $depth > 20) return;
    $seen[$n] = true;
    foreach ($deps[$n] ?? [] as $s) if (isset($svc[$s])) $visit($svc[$s], $depth + 1);
    $ordered[] = $n;
  };
  foreach ($names as $n) $visit($n);
  return array_values(array_intersect($ordered, $names));
}

/** Names of containers a job stops during backup. */
function bb_job_stop_targets(array $job): array {
  if (empty($job['stop']['enabled'])) return [];
  $src = $job['source'];
  if ($src['type'] === 'container') return [$src['name']];
  if ($src['type'] === 'compose') return array_column(bb_project_containers($src['name']), 'name');
  return array_values($job['stop']['containers'] ?? []);
}

