function bb_script_dir(): string { return bb_dir(BB_CFG . '/scripts'); }

function bb_valid_script_name($n): bool {
  return is_string($n) && preg_match('/^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/', $n) === 1 && substr($n, -3) === '.sh';
}

/** List library scripts with their description (first comment line). */
function bb_scripts(): array {
  $list = [];
  foreach (glob(bb_script_dir() . '/*.sh') ?: [] as $f) {
    $desc = '';
    foreach (array_slice(file($f, FILE_IGNORE_NEW_LINES) ?: [], 0, 6) as $l) {
      if (preg_match('/^#\s*(?!!)(.+)$/', $l, $m)) { $desc = trim($m[1]); break; }
    }
    $list[] = ['name' => basename($f), 'description' => $desc, 'size' => filesize($f), 'modified' => filemtime($f)];
  }
  return $list;
}

