/** Send an Unraid notification. $level: normal|warning|alert */
function bb_notify(string $subject, string $desc, string $level = 'normal'): void {
  $n = '/usr/local/emhttp/webGui/scripts/notify';
  if (!is_executable($n)) return;
  bb_exec([$n, '-e', 'Borg Backup', '-s', $subject, '-d', $desc, '-i', $level], [], ['timeout' => 30]);
}

/** Append a history entry (trimmed to history_keep). */
function bb_history_add(array $entry): void {
  $keep = (int)bb_settings()['history_keep'];
  bb_update('history', function ($h) use ($entry, $keep) {
    array_unshift($h, $entry);
    return array_slice($h, 0, max(50, $keep));
  });
}

/** Strip secrets before sending a repo to the browser. */
function bb_public_repo(array $r): array {
  $r['has_passphrase'] = !empty($r['passphrase']);
  unset($r['passphrase']);
  return $r;
}
