/** Default settings merged with what the user saved. */
function bb_settings(): array {
  return array_merge([
    'borg_bin'       => '',
    'cache_dir'      => '/mnt/user/appdata/borg-backup/cache',
    'log_dir'        => '/var/log/borg-backup',
    'ssh_key'        => BB_CFG . '/ssh/id_ed25519',
    'compression'    => 'zstd,3',
    'lock_wait'      => 600,
    'log_keep'       => 30,
    'history_keep'   => 500,
    'restore_dir'    => '/mnt/user/borg-restore',
    'notify_success' => false,
    'notify_warning' => true,
    'notify_failure' => true,
  ], bb_load('settings', []));
}

/** Resolve the borg executable: setting, plugin-installed binary, then PATH. */
function bb_borg_bin(): string {
  $s = bb_settings();
  foreach ([$s['borg_bin'], '/usr/local/bin/borg', '/usr/bin/borg'] as $c) {
    if ($c && is_file($c) && is_executable($c)) return $c;
  }
  $w = trim((string)@shell_exec('PATH=' . BB_PATH . ' command -v borg 2>/dev/null'));
  return $w ?: 'borg';
}

/** Borg cache dir; falls back to /tmp when the array (and appdata) is not available. */
function bb_cache_dir(): string {
  $c = bb_settings()['cache_dir'];
  if (strpos($c, '/mnt/') === 0) {
    $parts = explode('/', trim($c, '/'));
    $root = '/' . $parts[0] . '/' . ($parts[1] ?? '');
    if (!is_dir($root)) return BB_TMP . '/cache';
  }
  return $c;
}

/** Directory where run logs live. */
function bb_log_dir(): string {
  return bb_dir(rtrim(bb_settings()['log_dir'], '/') ?: '/var/log/borg-backup');
}

