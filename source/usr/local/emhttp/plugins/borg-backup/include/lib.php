/** Start the runner detached from the web request. */
function bb_spawn(array $args): void {
  $php = is_executable('/usr/bin/php') ? '/usr/bin/php' : 'php';
  $cmd = 'setsid nohup ' . $php . ' ' . escapeshellarg(BB_EMHTTP . '/include/runner.php') . ' '
       . implode(' ', array_map('escapeshellarg', $args)) . ' >/dev/null 2>&1 &';
  exec($cmd);
}

/** Currently running tasks (stale entries are cleaned up). */
function bb_tasks(): array {
  $tasks = [];
  foreach (glob(bb_dir(BB_RUN . '/tasks') . '/*.json') ?: [] as $f) {
    $t = json_decode((string)@file_get_contents($f), true);
    if (!$t || empty($t['pid']) || !file_exists('/proc/' . (int)$t['pid'])) { @unlink($f); continue; }
    $tasks[] = $t;
  }
  usort($tasks, fn($a, $b) => $a['started'] <=> $b['started']);
  return $tasks;
}

/** Is a given task key (e.g. job-abc123) running? */
function bb_task_running(string $key): bool {
  foreach (bb_tasks() as $t) if ($t['key'] === $key) return true;
  return false;
}

/** Ask a task to stop: flag file + SIGTERM to its current child (borg / script). */
function bb_task_cancel(string $key): bool {
  foreach (bb_tasks() as $t) {
    if ($t['key'] !== $key) continue;
    touch(BB_RUN . "/tasks/$key.cancel");
    if (!empty($t['child'])) @exec('kill -TERM ' . (int)$t['child'] . ' 2>/dev/null');
    return true;
  }
  return false;
}

