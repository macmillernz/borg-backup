define('BB_CFG', getenv('BB_TEST_ROOT') ? getenv('BB_TEST_ROOT') . '/cfg' : '/boot/config/plugins/borg-backup');
define('BB_RUN', getenv('BB_TEST_ROOT') ? getenv('BB_TEST_ROOT') . '/run' : '/var/run/borg-backup');
define('BB_TMP', getenv('BB_TEST_ROOT') ? getenv('BB_TEST_ROOT') . '/tmp' : '/tmp/borg-backup');
const BB_PATH   = '/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin';
