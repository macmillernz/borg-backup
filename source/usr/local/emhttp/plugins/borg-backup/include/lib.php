/** Find a repository by id. */
function bb_repo(string $id): ?array {
  foreach (bb_load('repos') as $r) if ($r['id'] === $id) return $r;
  return null;
}

/** Find a job by id. */
function bb_job(string $id): ?array {
  foreach (bb_load('jobs') as $j) if ($j['id'] === $id) return $j;
  return null;
}

/** Environment for talking to a repository (passphrase is passed via env, never argv). */
function bb_borg_env(array $repo): array {
  $s = bb_settings();
  $ssh = ['ssh', '-o', 'BatchMode=yes', '-o', 'StrictHostKeyChecking=accept-new',
          '-o', 'ServerAliveInterval=30', '-o', 'UserKnownHostsFile=' . BB_CFG . '/ssh/known_hosts'];
  $key = ($repo['ssh_key'] ?? '') ?: $s['ssh_key'];
  if ($key && is_file($key)) array_push($ssh, '-i', $key);
  bb_dir(BB_CFG . '/ssh');
  $env = [
    'BORG_REPO'        => $repo['location'],
    'BORG_PASSPHRASE'  => (string)($repo['passphrase'] ?? ''),
    'BORG_CONFIG_DIR'  => bb_dir(BB_CFG . '/borg'),
    'BORG_CACHE_DIR'   => bb_dir(bb_cache_dir()),
    'BORG_RSH'         => implode(' ', array_map('escapeshellarg', $ssh)),
    'BORG_UNKNOWN_UNENCRYPTED_REPO_ACCESS_IS_OK' => 'yes',
    'BORG_RELOCATED_REPO_ACCESS_IS_OK'           => 'yes',
    'BORG_EXIT_CODES'  => 'legacy',
  ];
  if (!empty($repo['remote_path'])) $env['BORG_REMOTE_PATH'] = $repo['remote_path'];
  return $env;
}

/** Run borg against a repo; returns [rc, stdout, stderr]. */
function bb_borg(array $repo, array $args, array $opt = []): array {
  $rc = bb_exec(array_merge([bb_borg_bin()], $args), bb_borg_env($repo), $opt + ['timeout' => 300], $out, $err);
  return [$rc, $out, $err];
}

/** Last meaningful error line from borg stderr. */
function bb_borg_error(string $err): string {
  $lines = array_values(array_filter(array_map('trim', explode("\n", $err))));
  return $lines ? implode("\n", array_slice($lines, -4)) : 'Unknown error';
}

/** Installed borg version string, or null. */
function bb_borg_version(): ?string {
  $rc = bb_exec([bb_borg_bin(), '--version'], [], ['timeout' => 15], $out);
  return $rc === 0 ? trim($out) : null;
}

/** Refresh and cache repository statistics. */
function bb_repo_refresh(array $repo): array {
  [$rc, $out, $err] = bb_borg($repo, ['info', '--json', '--bypass-lock'], ['timeout' => 120]);
  if ($rc !== 0) {
    $info = ['ok' => false, 'error' => bb_borg_error($err), 'checked' => time()];
  } else {
    $j = json_decode($out, true) ?: [];
    $st = $j['cache']['stats'] ?? [];
    [$rc2, $out2] = bb_borg($repo, ['list', '--json', '--bypass-lock'], ['timeout' => 120]);
    $arch = $rc2 === 0 ? (json_decode($out2, true)['archives'] ?? []) : [];
    $last = $arch ? end($arch) : null;
    $info = [
      'ok' => true, 'checked' => time(),
      'archives' => count($arch),
      'last_archive' => $last['name'] ?? null,
      'last_time' => isset($last['time']) ? strtotime($last['time']) : null,
      'original' => $st['total_size'] ?? 0,
      'compressed' => $st['total_csize'] ?? 0,
      'deduplicated' => $st['unique_csize'] ?? 0,
      'encryption' => $j['encryption']['mode'] ?? null,
    ];
  }
  bb_update('status', function ($s) use ($repo, $info) { $s['repos'][$repo['id']] = $info; return $s; });
  return $info;
}

